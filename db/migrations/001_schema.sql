-- Prospect Flow · 001 · schema `crm`
--
-- Só o papel `crm_api` (a API) recebe permissão neste schema. O papel nasce
-- NOLOGIN e sem senha: quem instala liga o login e define a senha fora do
-- repositório (db/docker/10_papel_api.sh faz isso no `docker compose up`):
--   alter role crm_api with login password '<senha forte>';

create schema if not exists crm;

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'crm_api') then
    create role crm_api nologin;
  end if;
end $$;

revoke all on schema crm from public;
grant usage on schema crm to crm_api;

create or replace function crm.tocar_atualizado_em() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

-- ── Operadores ──────────────────────────────────────────────────────────────
create table if not exists crm.operadores (
  email          text primary key,
  nome           text not null,
  admin          boolean not null default false,
  caixa          text,                       -- caixa de e-mail que envia/recebe a prospecção
  bcc            text,
  regras         jsonb not null default '{}'::jsonb,
  ativo          boolean not null default true,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);

-- ── Leads (uma empresa = um domínio) ─────────────────────────────────────────
create table if not exists crm.leads (
  id                   bigint generated by default as identity primary key,
  dominio              text not null unique,
  empresa              text,
  cnpj                 text,
  endereco             text,
  telefone_geral       text,
  primeiro_envio       timestamptz,
  ultimo_envio         timestamptz,
  ultimo_contato_em    timestamptz,
  teve_resposta        boolean not null default false,
  estagio_funil        text not null default 'frio'
    check (estagio_funil in ('frio','aquecendo','respondeu','qualificado','proposta_enviada','convertido','descartado')),
  estagio_mudou_em     timestamptz,
  proximo_followup_em  timestamptz,
  rodada_atual         smallint not null default 0,   -- última rodada (R1..R3) do ciclo corrente
  ciclo                smallint not null default 1,
  dono_email           text references crm.operadores(email),
  responsavel_bot      text,
  observacao           text,
  criado_em            timestamptz not null default now(),
  atualizado_em        timestamptz not null default now()
);
create index if not exists leads_dono_followup on crm.leads (dono_email, proximo_followup_em);
create index if not exists leads_estagio on crm.leads (estagio_funil);

create table if not exists crm.contatos (
  id         bigint generated by default as identity primary key,
  lead_id    bigint not null references crm.leads(id) on delete cascade,
  nome       text,
  email      text not null,
  cargo      text,
  telefone   text,
  origem     text not null default 'prospeccao',
  invalido   boolean not null default false,              -- bounce confirmado
  criado_em  timestamptz not null default now()
);
create index if not exists contatos_lead on crm.contatos (lead_id);
create unique index if not exists contatos_lead_email on crm.contatos (lead_id, lower(email));

create table if not exists crm.interacoes (
  id               bigint generated by default as identity primary key,
  lead_id          bigint not null references crm.leads(id) on delete cascade,
  email            text,
  nome             text,
  telefone         text,
  data_interacao   timestamptz,
  assunto          text,
  trecho           text,
  canal            text not null default 'email',
  direcao          text not null default 'recebido' check (direcao in ('enviado','recebido')),
  origem           text not null default 'importacao',        -- importacao | api | bot
  message_id       text,
  classe           text,                                   -- humano | bounce | auto_reply | redirect
  interesse        text,                                   -- real | generico (classificação)
  criado_em        timestamptz not null default now()
);
create index if not exists interacoes_lead on crm.interacoes (lead_id, data_interacao desc);
create unique index if not exists interacoes_message_id on crm.interacoes (message_id) where message_id is not null;

-- ── Tarefas (fila + quadro) ─────────────────────────────────────────────────
create table if not exists crm.tarefas (
  id                   uuid primary key default gen_random_uuid(),
  operador             text not null references crm.operadores(email),
  tipo                 text not null check (tipo in ('envio_diario','tratar_resposta','campainha','acompanhamento','resposta_operador','pergunta')),
  status               text not null default 'pendente'
    check (status in ('pendente','entregue','em_andamento','executou','parcial','adiou','recusou','bloqueado_humano','falhou','cancelada')),
  prioridade           text not null default 'normal' check (prioridade in ('normal','urgente')),
  titulo               text not null,
  lead_id              bigint references crm.leads(id),
  payload              jsonb not null default '{}'::jsonb,
  resposta             jsonb,
  motivo               text,
  detalhe              text,
  origem               text not null default 'orquestrador' check (origem in ('orquestrador','operador','bot','sistema')),
  criada_por           text not null,
  criada_em            timestamptz not null default now(),
  entregue_em          timestamptz,
  iniciada_em          timestamptz,
  concluida_em         timestamptz,
  reagendar_em         timestamptz,
  prazo                timestamptz,
  tentativas_entrega   smallint not null default 0,
  ultimo_erro_entrega  text,
  campainha_id         uuid,
  acompanhamento_id    uuid,
  relato_id            uuid,
  chave_dedup          text unique,                         -- impede tarefa duplicada (ex.: envio_diario:<op>:<data>)
  atualizado_em        timestamptz not null default now()
);
create index if not exists tarefas_operador_status on crm.tarefas (operador, status, criada_em desc);
create index if not exists tarefas_lead on crm.tarefas (lead_id);

-- ── Ações no lead (histórico de toques) ─────────────────────────────────────
create table if not exists crm.acoes (
  id               bigint generated by default as identity primary key,
  lead_id          bigint not null references crm.leads(id) on delete cascade,
  tipo_acao        text not null,
  descricao        text,
  rodada           smallint,                                 -- 1..3 quando é toque de rodada
  data_hora        timestamptz not null default now(),
  proxima_acao_em  timestamptz,
  realizado_por    text not null,
  tarefa_id        uuid references crm.tarefas(id),
  envio_id         uuid,
  criado_em        timestamptz not null default now()
);
create index if not exists acoes_lead on crm.acoes (lead_id, data_hora desc);

-- ── Envios (rascunho do bot → validado → enviado pelo n8n) ──────────────────
create table if not exists crm.envios (
  id               uuid primary key default gen_random_uuid(),
  tarefa_id        uuid references crm.tarefas(id),
  operador         text not null references crm.operadores(email),
  lead_id          bigint not null references crm.leads(id),
  tipo_envio       text not null check (tipo_envio in ('R1','R2','R3','reenvio_pos_bounce','redirect_auto_reply','resposta_in_thread')),
  rodada           smallint,
  para             text not null,
  assunto          text not null,
  corpo_html       text not null,
  anexos           text[] not null default '{}',
  in_reply_to      text,
  proxima_acao_em  timestamptz,
  status           text not null default 'aprovado'
    check (status in ('aprovado','agendado','bloqueado','enviando','enviado','falhou','cancelado')),
  motivo_bloqueio  text,
  liberado_por     text,
  enviar_apos      timestamptz,
  message_id       text,
  enviado_em       timestamptz,
  erro             text,
  tentativas       smallint not null default 0,
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now()
);
create index if not exists envios_status on crm.envios (status, enviar_apos);
create index if not exists envios_operador_dia on crm.envios (operador, enviado_em);

-- ── Campainhas ──────────────────────────────────────────────────────────────
create table if not exists crm.campainhas (
  id                uuid primary key default gen_random_uuid(),
  operador          text not null references crm.operadores(email),
  nome              text not null,
  tipo              text not null check (tipo in ('dominio','remetente','assunto')),
  padrao            text not null,
  caixa             text,                                    -- null = caixa do operador
  prioridade        text not null default 'urgente' check (prioridade in ('normal','urgente')),
  instrucao         text,
  lead_id           bigint references crm.leads(id),
  ativa             boolean not null default true,
  criada_por        text not null,
  criada_por_tipo   text not null check (criada_por_tipo in ('operador','bot')),
  criada_em         timestamptz not null default now(),
  arquivada_em      timestamptz,
  arquivada_por     text,
  expira_em         timestamptz,
  disparos          integer not null default 0,
  ultimo_disparo_em timestamptz,
  atualizado_em     timestamptz not null default now()
);

create table if not exists crm.campainha_disparos (
  id            bigint generated by default as identity primary key,
  campainha_id  uuid not null references crm.campainhas(id) on delete cascade,
  message_id    text not null,
  de            text,
  assunto       text,
  trecho        text,
  recebido_em   timestamptz,
  tarefa_id     uuid references crm.tarefas(id),
  criado_em     timestamptz not null default now(),
  unique (campainha_id, message_id)
);

-- ── Acompanhamentos ─────────────────────────────────────────────────────────
create table if not exists crm.acompanhamentos (
  id                uuid primary key default gen_random_uuid(),
  operador          text not null references crm.operadores(email),
  lead_id           bigint references crm.leads(id),
  titulo            text not null,
  instrucao         text,
  agendado_para     timestamptz not null,
  repetir_dias      smallint check (repetir_dias is null or repetir_dias between 1 and 365),
  status            text not null default 'agendado' check (status in ('agendado','disparado','concluido','cancelado')),
  criado_por        text not null,
  criado_por_tipo   text not null check (criado_por_tipo in ('operador','bot')),
  criado_em         timestamptz not null default now(),
  ultimo_disparo_em timestamptz,
  tarefa_id         uuid references crm.tarefas(id),
  atualizado_em     timestamptz not null default now()
);
create index if not exists acompanhamentos_vencidos on crm.acompanhamentos (status, agendado_para);

-- ── Relatos (bot → operador) ────────────────────────────────────────────────
create table if not exists crm.relatos (
  id              uuid primary key default gen_random_uuid(),
  operador        text not null references crm.operadores(email),
  tipo            text not null check (tipo in ('info','alerta','pergunta','pedido_autorizacao')),
  titulo          text not null,
  corpo           text,
  lead_id         bigint references crm.leads(id),
  tarefa_id       uuid references crm.tarefas(id),
  urgente         boolean not null default false,
  criado_por      text not null,
  criado_em       timestamptz not null default now(),
  lido_em         timestamptz,
  resposta        text,
  respondido_em   timestamptz,
  respondido_por  text,
  avisado_em      timestamptz                                -- n8n já notificou o operador
);
create index if not exists relatos_operador on crm.relatos (operador, criado_em desc);

-- ── Diretrizes versionadas ──────────────────────────────────────────────────
create table if not exists crm.diretrizes (
  id            uuid primary key default gen_random_uuid(),
  operador      text references crm.operadores(email),       -- null = padrão da casa
  versao        integer not null,
  status        text not null check (status in ('ativa','proposta','rejeitada','substituida')),
  conteudo      text not null,
  regras        jsonb,
  autor         text not null,
  autor_tipo    text not null check (autor_tipo in ('operador','bot','sistema')),
  motivo        text,
  base_versao   integer,
  decidida_por  text,
  decidida_em   timestamptz,
  nota_decisao  text,
  criada_em     timestamptz not null default now(),
  unique (operador, versao)
);
create unique index if not exists diretrizes_uma_ativa on crm.diretrizes (coalesce(operador, '*')) where status = 'ativa';

-- ── Chaves de API e bots ────────────────────────────────────────────────────
create table if not exists crm.chaves_api (
  id            uuid primary key default gen_random_uuid(),
  hash_sha256   text not null unique,
  prefixo       text not null,                               -- primeiros caracteres, para reconhecer na tela
  nome          text not null,
  operador      text references crm.operadores(email),       -- null só para orquestrador
  escopo        text not null check (escopo in ('bot','orquestrador','leitura')),
  ativa         boolean not null default true,
  criada_em     timestamptz not null default now(),
  ultimo_uso_em timestamptz,
  check (escopo = 'orquestrador' or operador is not null)
);

create table if not exists crm.bots (
  operador         text primary key references crm.operadores(email),
  nome             text not null,
  webhook_url      text,
  webhook_segredo  text,                                     -- HMAC; nunca devolvido depois de criado
  ativo            boolean not null default true,
  atualizado_em    timestamptz not null default now()
);

-- ── Auditoria ───────────────────────────────────────────────────────────────
create table if not exists crm.eventos (
  id          bigint generated by default as identity primary key,
  em          timestamptz not null default now(),
  ator        text not null,
  ator_tipo   text not null check (ator_tipo in ('operador','bot','orquestrador','sistema')),
  operador    text,
  acao        text not null,
  entidade    text not null,
  entidade_id text,
  dados       jsonb
);
create index if not exists eventos_em on crm.eventos (em desc);
create index if not exists eventos_entidade on crm.eventos (entidade, entidade_id);

-- ── Gatilhos de atualizado_em ───────────────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['operadores','leads','tarefas','envios','campainhas','acompanhamentos','bots'] loop
    execute format('drop trigger if exists tocar_atualizado_em on crm.%I', t);
    execute format('create trigger tocar_atualizado_em before update on crm.%I for each row execute function crm.tocar_atualizado_em()', t);
  end loop;
end $$;

